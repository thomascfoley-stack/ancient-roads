#!/usr/bin/env node
// A8 ACT 3 FLIP LIST — derived from the copy batches minus the works standing rulings HOLD.
//
// Hand-typing this list would be the repo's most-repeated defect applied to its most irreversible
// operation, so every slug comes from the same batch files the copier used, and every EXCLUSION
// names the ruling that made it. A held work with no cited ruling is a bug in this script.
import fs from 'node:fs';
import path from 'node:path';
import { isMustNotServeAuthor } from '../web/src/lib/legal-corpus.ts';

const REPO = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const BATCHES = ['hymns', 'poetry', 'sermons', 'remaining-nonsermon'];
const manifest = JSON.parse(fs.readFileSync(path.join(REPO, 'ingest/sources.config.json'), 'utf8'));
const bySlug = new Map(Object.values(manifest).filter((e) => e?.slug).map((e) => [e.slug, e]));

// The standing rulings, each with the document that issued it. NOT a taste list.
const HELD = new Map([
  ['bdb-lexicon',        'DECISIONS.md "Lexicons: pane" — stay staged until the reference-pane UX ships'],
  ['eastons-dictionary', 'DECISIONS.md "Lexicons: pane" — stay staged until the reference-pane UX ships'],
  ['isbe',               'DECISIONS.md "Lexicons: pane" — stay staged until the reference-pane UX ships'],
  ['naves-topical',      'DECISIONS.md "Lexicons: pane" — stay staged until the reference-pane UX ships'],
  ['smiths-dictionary',  'DECISIONS.md "Lexicons: pane" — stay staged until the reference-pane UX ships'],
]);

const slugs = [], held = [];
for (const b of BATCHES) {
  for (const slug of JSON.parse(fs.readFileSync(path.join(REPO, `docs/evidence/corpus-copy/${b}.json`), 'utf8')).slugs) {
    const author = bySlug.get(slug)?.author ?? '';
    // The BAN is checked with the shipped predicate, not restated: it normalises
    // "Origen of Alexandria" ~ 'Origen', which a literal list here would miss.
    if (isMustNotServeAuthor(author)) { held.push(`${slug}: MUST_NOT_SERVE_AUTHORS (${author}) — A6 ruling 2026-07-17`); continue; }
    if (HELD.has(slug)) { held.push(`${slug}: ${HELD.get(slug)}`); continue; }
    slugs.push(slug);
  }
}
slugs.sort();
const out = {
  _: 'A8 act 3 flip list. GENERATED by scripts/build-a8-flip-list.mjs — re-run it rather than editing by hand.',
  builtFor: 'A8 act 3 — publish the registers copied on 2026-08-02',
  host: 'ep-odd-fog-atnykudm',
  cohort: 'staged',
  held,
  slugs,
};
const file = path.join(REPO, 'docs/evidence/corpus-copy/a8-flip-list.json');
fs.writeFileSync(file, `${JSON.stringify(out, null, 2)}\n`);
console.log(`${slugs.length} work(s) to publish, ${held.length} held\n`);
console.log(slugs.join(', '));
console.log('\nHELD, each with the ruling that holds it:');
for (const h of held) console.log(`  ${h}`);
console.log(`\nwrote ${path.relative(REPO, file)}`);
